-- 每次新连接都要先切到可读写的用户库，否则会在根库里建表
ALTER SESSION SET CONTAINER = FREEPDB1;

-- 让输出不至于挤成一团
SET LINESIZE 200
SET PAGESIZE 100


-- ============================================================
-- ① 建一张表：医院智能衣鞋柜的设备台账
-- ============================================================
CREATE TABLE 设备台账 (
  设备编号   VARCHAR2(20) PRIMARY KEY,   -- 主键：不能重复、不能为空
  医院名称   VARCHAR2(50) NOT NULL,      -- NOT NULL：必填
  型号       VARCHAR2(30),
  装机日期   DATE,
  状态       VARCHAR2(10)
);


-- ============================================================
-- ② 插入四条数据（换成你自己工作里遇到的真实设备，会更有感觉）
-- ============================================================
INSERT INTO 设备台账 VALUES ('SB-001', '长春自强院区', 'GX-2000', DATE '2025-03-15', '正常');
INSERT INTO 设备台账 VALUES ('SB-002', '长春自强院区', 'GX-2000', DATE '2025-06-20', '维修中');
INSERT INTO 设备台账 VALUES ('SB-003', '长春自强院区', 'GX-3000', DATE '2025-08-01', '正常');
INSERT INTO 设备台账 VALUES ('SB-004', '长春自强院区', 'GX-3000', DATE '2025-09-10', '已停用');

COMMIT;   -- 确认写入（Oracle 默认不会自动提交）


-- ============================================================
-- ③ 全部查出来
-- ============================================================
SELECT * FROM 设备台账;


-- ============================================================
-- ④ 加条件：只看维修中的设备
-- ============================================================
SELECT 设备编号, 型号
FROM   设备台账
WHERE  状态 = '维修中';


-- ============================================================
-- ⑤ 排序：按装机日期从新到旧
-- ============================================================
SELECT 设备编号,
       TO_CHAR(装机日期, 'YYYY-MM-DD') AS 装机日期,
       状态
FROM   设备台账
ORDER BY 装机日期 DESC;


-- ============================================================
-- ⑥ 分组统计：每种状态各有几台
-- ============================================================
SELECT 状态, COUNT(*) AS 台数
FROM   设备台账
GROUP BY 状态
ORDER BY 台数 DESC;


