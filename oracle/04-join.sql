--  上一篇（03）我们把表搬到了自己名下。今天学 SQL 里最值钱的一块：
--  「数据散在多张表里，怎么拼成一张能看的表」。
--
--  为什么必须拆表：
--    一台设备会修很多次。如果维修记录跟设备台账塞在同一张表里，
--    设备信息（医院、型号）就要跟着重复写很多遍 —— 改一个医院名
--    得改十几行，还容易改漏。所以「一个东西一条记录」拆成两张表，
--    查的时候再用 JOIN 拼回来。
--
--  运行方式（DBeaver 里：选中一段按 Alt+X 单独执行，别整篇跑）：
--    先执行 ① 建工单表并插数据，再往下逐段执行、逐段看结果。
