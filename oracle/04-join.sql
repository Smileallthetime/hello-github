PROMPT ===== 维修工单（8 张工单）=====
SELECT 工单号, 设备编号, TO_CHAR(报修日期,'YYYY-MM-DD') AS 报修日期, 故障现象, 处理人, 完成状态
FROM   study.维修工单
ORDER  BY 工单号;


-- ============================================================
-- ④ JOIN 长什么样 —— 一行一行拆开读
--
--    SELECT   d.设备编号,  w.故障现象
--    FROM     设备台账 d          ← d 是这张表的「小名」（别名）
--    JOIN     维修工单 w          ← JOIN = 把两张表拼起来
--      ON     d.设备编号 = w.设备编号   ← 拼接规则：两边的设备编号相等
--
--    ① d / w 是别名。两张表都有「设备编号」这一列，
--       不写别名，Oracle 分不清你说的是哪张表的，会报 ORA-00918。
--    ② ON 后面的等式就是「关联条件」，也叫「连接条件」—— 灵魂就是它。
--    ③ SELECT 里写 d.设备编号 还是 w.设备编号 都行，
--       因为按 ON 的规则，这两列相等的行才会留下。
-- ============================================================
PROMPT ===== ④ 第一次关联：设备台账 JOIN 维修工单 =====
SELECT d.设备编号, d.型号, w.工单号, w.故障现象, w.处理人
FROM   study.设备台账 d
JOIN   study.维修工单 w
  ON   d.设备编号 = w.设备编号
ORDER  BY d.设备编号, w.工单号;


-- ============================================================
-- ⑤ JOIN 的默认行为 = 内连接（INNER JOIN）
--    「只保留两边都对得上的行」
--    结果 7 行 —— 不是 5（设备数），也不是 8（工单数）：
--      SB-004 没有工单      → 掉出去了（左边对不上）
--      GD-008 的设备不存在  → 掉出去了（右边对不上）
--    JOIN 和 INNER JOIN 是同一个东西，写哪个都行。
-- ============================================================


-- ============================================================
-- ⑥ LEFT JOIN（左连接）：左边的表一行都不能少
--    左边是「设备台账」→ 5 台设备必须全在，对不上工单的地方填 NULL
--    ↑ 结果 8 行：SB-004 也出来了，工单那几列是空的
-- ============================================================
PROMPT ===== ⑥ LEFT JOIN：5 台设备都保留 =====
SELECT d.设备编号, d.型号, w.工单号, w.故障现象, w.处理人
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
ORDER  BY d.设备编号, w.工单号;


-- ============================================================
-- ⑦ ⚠️ 新手最常踩的坑：把过滤条件写在 WHERE 里，LEFT JOIN 会白写
--
--    本意：「列出所有设备，以及其中已经处理完的工单」
--    错误写法（把 w 表的条件放进 WHERE）：
--
--      ... LEFT JOIN study.维修工单 w
--            ON d.设备编号 = w.设备编号
--          WHERE w.完成状态 = '已完成'
--
--    结果 5 行，只剩「有已完成工单的设备」——
--    SB-004（没工单）、SB-005（只有处理中的工单）全不见了，
--    等于把 LEFT JOIN 退化成了 INNER JOIN，白写。
--    原因：对不上的行，w.完成状态 是 NULL；
--          WHERE 拿 NULL 去比 '已完成'，比不成立，整行被删掉。
--    ★ 一句话记住：
--       「LEFT JOIN 之后，右表的条件写在 ON 里，别写在 WHERE 里。」
-- ============================================================
PROMPT ===== ⑦-错误写法：条件写进 WHERE（SB-004、SB-005 消失，只剩 5 行）=====
SELECT d.设备编号, d.型号, w.工单号, w.完成状态
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
WHERE  w.完成状态 = '已完成'
ORDER  BY d.设备编号;

PROMPT ===== ⑦-正确写法：条件写在 ON 里（5 台设备全在）=====
SELECT d.设备编号, d.型号, w.工单号, w.完成状态
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
 AND   w.完成状态 = '已完成'
ORDER  BY d.设备编号;


-- ============================================================
-- ⑧ 找出「对不上」的行 —— 这是 LEFT JOIN 最实用的一招
--    查完发现谁缺了，就能直接去补数据 / 去问人。
--    IS NULL 判断空值，只能写 IS NULL，不能写 = NULL。
-- ============================================================
PROMPT ===== ⑧ 从没修过的设备（工单号为空）=====
SELECT d.设备编号, d.型号, d.状态
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
WHERE  w.工单号 IS NULL;

PROMPT ===== ⑧ 设备编号在台账里查不到的「野工单」=====
SELECT w.工单号, w.设备编号, w.故障现象
FROM   study.维修工单 w
LEFT JOIN study.设备台账 d
  ON   w.设备编号 = d.设备编号
WHERE  d.设备编号 IS NULL;


-- ============================================================
-- ⑨ 关联 + 分组统计：每台设备修了几次
--    LEFT JOIN 配 COUNT(具体列) ——
--      COUNT(*)        会把「空行」也数成 1，SB-004 会变成 1 次（错！）
--      COUNT(w.工单号) 空行不算数，SB-004 是 0 次（对）
-- ============================================================
PROMPT ===== ⑨ 每台设备的维修次数（没修过的显示 0）=====
SELECT d.设备编号, d.型号, COUNT(w.工单号) AS 维修次数
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
GROUP  BY d.设备编号, d.型号
ORDER  BY 维修次数 DESC, d.设备编号;


-- ============================================================
-- ⑩ 按故障现象统计：哪种毛病最常见（← 这条最接近你工作里要的东西）
-- ============================================================
PROMPT ===== ⑩ 故障现象排行榜 =====
SELECT w.故障现象, COUNT(*) AS 次数
FROM   study.维修工单 w
GROUP  BY w.故障现象
ORDER  BY 次数 DESC, w.故障现象;


-- ============================================================
-- ⑪ 把关联结果当成一张「能看的表」
--    关联最大的用处就是这个：拼完之后，工单里没有的信息
--    （医院、型号、设备状态）全都能看到了，你才能按它筛选、统计。
--    想看三张表怎么连？继续往后接 JOIN 就行，一个 ON 管一次连接：
--      FROM 工单 w JOIN 设备 d ON ... JOIN 医院 h ON ...
--    （本练习里医院信息就在台账表内，所以这里只连两张。明天要的话
--      我们再建第三张表，那时会真写一次三表连接。）
-- ============================================================
PROMPT ===== ⑪ 工单 + 设备 + 医院（本例医院在台账里，先看两段拼接）=====
SELECT w.工单号, w.故障现象, w.处理人, d.医院名称, d.型号, d.状态
FROM   study.维修工单 w
JOIN   study.设备台账 d
  ON   w.设备编号 = d.设备编号
ORDER  BY w.工单号;


