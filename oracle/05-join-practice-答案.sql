ALTER SESSION SET CONTAINER = FREEPDB1;
SET LINESIZE 160
SET PAGESIZE 100


-- ------------------------------------------------------------
-- 任务 1：每张工单 + 设备型号 + 医院名称
--   7 行（GD-008 的设备不存在，被 JOIN 挡掉了）
-- ------------------------------------------------------------
SELECT w.工单号, w.故障现象, d.型号, d.医院名称
FROM   study.维修工单 w
JOIN   study.设备台账 d
  ON   w.设备编号 = d.设备编号
ORDER  BY w.工单号;


-- ------------------------------------------------------------
-- 任务 2：所有「处理中」的工单
--   2 行：GD-004（SB-002）、GD-007（SB-005）
--   这里 JOIN 和 LEFT JOIN 结果一样 —— 因为条件是「筛掉不要的」，
--   而且筛的是右表里本来就存在工单的行。
--   ★ 判断口诀：条件是用来「筛掉行」的，放 WHERE；
--              条件是「右表对不上也要留」的，放 ON。
-- ------------------------------------------------------------
SELECT w.工单号, d.设备编号, d.型号, w.故障现象, w.完成状态
FROM   study.维修工单 w
JOIN   study.设备台账 d
  ON   w.设备编号 = d.设备编号
WHERE  w.完成状态 = '处理中'
ORDER  BY w.工单号;


-- ------------------------------------------------------------
-- 任务 3：SB-001 修过几次、什么毛病
--   2 行：GD-001 触摸屏黑屏、GD-002 柜门锁打不开
-- ------------------------------------------------------------
SELECT d.设备编号, w.工单号, TO_CHAR(w.报修日期,'YYYY-MM-DD') AS 报修日期, w.故障现象, w.处理人
FROM   study.设备台账 d
JOIN   study.维修工单 w
  ON   d.设备编号 = w.设备编号
WHERE  d.设备编号 = 'SB-001'
ORDER  BY w.工单号;


-- ------------------------------------------------------------
-- 任务 4：已停用、但还有处理中工单的设备
--   1 行：SB-002 / GD-004
--   从设备台账出发，因为「已停用」这个条件在台账上。
-- ------------------------------------------------------------
SELECT d.设备编号, d.型号, d.状态, w.工单号, w.故障现象, w.完成状态
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w
  ON   d.设备编号 = w.设备编号
WHERE  d.状态 = '已停用'
 AND   w.完成状态 = '处理中';


-- ------------------------------------------------------------
-- 任务 5：每个处理人各处理多少张工单
--   张工 3、李工 3、王工 2（含 GD-008 那张「野工单」）
-- ------------------------------------------------------------
SELECT w.处理人, COUNT(*) AS 张数
FROM   study.维修工单 w
GROUP  BY w.处理人
ORDER  BY 张数 DESC, w.处理人;


-- ------------------------------------------------------------
-- 任务 6（挑战）：每台设备最后一次报修日期
--   LEFT JOIN 版 5 行：SB-004 显示空（从没修过也要列出来）
--   JOIN      版 4 行：SB-004 直接不出现
--   两种都对，看你要回答什么问题 —— 这就是 JOIN 选择的分水岭。
-- ------------------------------------------------------------
-- 想要「每台设备都出现」：
SELECT d.设备编号, TO_CHAR(MAX(w.报修日期),'YYYY-MM-DD') AS 最后一次报修
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w ON d.设备编号 = w.设备编号
GROUP  BY d.设备编号
ORDER  BY d.设备编号;

-- 只想看「有维修记录的设备」：
SELECT d.设备编号, TO_CHAR(MAX(w.报修日期),'YYYY-MM-DD') AS 最后一次报修
FROM   study.设备台账 d
JOIN   study.维修工单 w ON d.设备编号 = w.设备编号
GROUP  BY d.设备编号
ORDER  BY d.设备编号;


-- ============================================================
--  多出来的一个知识点：COUNT(*) 和 COUNT(某列) 不一样
--    LEFT JOIN 之后：
--      COUNT(*)          把「没工单的那行」也数成 1  → SB-004 变成 1 次（错）
--      COUNT(w.工单号)   空值不数              → SB-004 是 0 次（对）
-- ------------------------------------------------------------
SELECT d.设备编号,
       COUNT(*)         AS 全数,
       COUNT(w.工单号)  AS 只数真工单
FROM   study.设备台账 d
LEFT JOIN study.维修工单 w ON d.设备编号 = w.设备编号
GROUP  BY d.设备编号
ORDER  BY d.设备编号;
