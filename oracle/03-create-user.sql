-- ============================================================
--  Oracle 练习 03：给自己建一个账号（模式）
-- ============================================================
--  用途：
--    在新环境里给自己开一块独立的数据库空间。
--    真实工作中「给新项目 / 新同事开数据库空间」就是这个流程。
--
--  执行方式（在 DBeaver 里）：
--    一行一行选中，按 Alt+X 单独执行。不要整个脚本一起跑。
--
--  ⚠️⚠️ 安全提醒（很重要）：
--    下面「换成你的密码」处是占位符，不要把真实密码写进这个文件！
--    因为这个文件会提交到 GitHub —— 一旦提交，密码就永远留在历史记录里。
--    真实密码记在自己脑子里，或者用密码管理器。
--    这是行业的铁律：密码、密钥、令牌，绝不进代码、绝不进 Git。
-- ============================================================


-- ------------------------------------------------------------
-- ① 建账号
--    CREATE = 从无到有。账号已存在时会报 ORA-01920，
--    那时候改用：ALTER USER study IDENTIFIED BY 你的密码;
-- ------------------------------------------------------------
CREATE USER study IDENTIFIED BY 换成你的密码;


-- ------------------------------------------------------------
-- ② 授权 + 给空间
--    CONNECT  = 能登录
--    RESOURCE = 能建表、建视图
--    QUOTA    = 允许在 USERS 表空间里用空间
--               （不设的话，建表会报 ORA-01950 配额不足）
-- ------------------------------------------------------------
GRANT CONNECT, RESOURCE TO study;
ALTER USER study QUOTA UNLIMITED ON USERS;


-- ------------------------------------------------------------
-- ③ 把别的模式下的表搬到自己名下
--
--    CTAS（CREATE TABLE AS SELECT）复制什么、不复制什么：
--      ✅ 数据
--      ✅ NOT NULL 约束
--      ❌ 主键、索引、外键  ← 必须手动补
--    原因：约束和索引是「建在表上的额外设施」，不是表本身。
-- ------------------------------------------------------------
CREATE TABLE study.设备台账 AS SELECT * FROM SYS.设备台账;
ALTER TABLE study.设备台账 ADD CONSTRAINT pk_device PRIMARY KEY (设备编号);


-- ------------------------------------------------------------
-- ④ 验证 —— 顺序绝不能反
--    先建新的 → 验证新表有数据 → 再删旧的
--    万一复制失败就先删了旧表，数据就没了。
-- ------------------------------------------------------------
SELECT COUNT(*) AS 新表行数 FROM study.设备台账;

