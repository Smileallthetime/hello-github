--  想让它能反复跑，在 CREATE 之前加这一段：
--
--    BEGIN
--      EXECUTE IMMEDIATE 'DROP TABLE study.设备台账';
--    EXCEPTION WHEN OTHERS THEN NULL;   -- 不存在就算了，不报错
--    END;
--    /
--
--  这叫「幂等」：跑一遍和跑十遍，结果一样。
